import React, { useState, useEffect } from 'react';
import Header from '../components/Header';
import { FileText } from 'lucide-react';

export default function Reports() {
  const [reportsText, setReportsText] = useState("");
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch('/assets/country_risk_reports.txt')
      .then(res => res.text())
      .then(text => {
        setReportsText(text);
        setLoading(false);
      })
      .catch(err => {
        console.error("Error loading reports:", err);
        setLoading(false);
      });
  }, []);

  // Simple parser to separate the text into chunks/cards based on "=================================================="
  const renderReports = () => {
    if (!reportsText) return null;
    
    const chunks = reportsText.split('==================================================');
    
    return chunks.map((chunk, idx) => {
      if (chunk.trim().length < 10) return null;
      return (
        <div key={idx} className="chart-card" style={{ marginBottom: '24px', whiteSpace: 'pre-wrap', fontFamily: 'monospace', fontSize: '14px', lineHeight: '1.5' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '16px', color: 'var(--color-primary)', borderBottom: '1px solid var(--border-color)', paddingBottom: '12px' }}>
            <FileText size={20} />
            <h3 style={{ margin: 0, fontSize: '16px', color: 'var(--text-primary)' }}>Agentic AI Risk Assessment</h3>
          </div>
          {chunk.trim()}
        </div>
      );
    });
  };

  return (
    <div className="main-content">
      <Header title="Agentic AI Reports" />
      
      <div className="content-wrapper" style={{maxWidth: '1000px', margin: '0 auto', width: '100%'}}>
        <p style={{color: 'var(--text-secondary)', marginBottom: '24px'}}>
          These reports are autonomously generated by the Agentic AI using the trained ML models and real-time inference data.
        </p>
        
        {loading ? (
          <p>Loading reports...</p>
        ) : (
          <div>{renderReports()}</div>
        )}
      </div>
    </div>
  );
}
